#!/usr/bin/env python3
"""v1.5.3-e: generate cpmap_intro_clip.h, the startup clip the CarPlay bridge plays before the live map.
The clip is an 800x480 Constrained Baseline Annex-B H.264 stream at 30 fps (VUI time_scale 60), one AUD per access unit,
an IDR with SPS/PPS every 14 frames, no B-frames. The bridge sends it unchanged through its TS muxer: no decode or
re-encode on the unit. --check compares an existing header with the clip instead of writing it.
Usage: make-intro-header.py CLIP.h264 HEADER.h [--check]
SPDX-License-Identifier: GPL-3.0-or-later
"""
import hashlib, sys
from pathlib import Path

def render(clip):
    data = clip.read_bytes()
    aud = sum(1 for i in range(len(data) - 4) if data[i:i + 4] == b'\0\0\0\1' and data[i + 4] & 0x1f == 9)
    assert data[:5] == b'\0\0\0\1\x09' and aud > 0, 'clip must start with an AUD'
    lines = ['/* Generated by tools/make-intro-header.py from intro/%s. Do not edit. */' % clip.name,
             '/* sha256=%s bytes=%d access_units=%d */' % (hashlib.sha256(data).hexdigest(), len(data), aud),
             '#ifndef CPMAP_INTRO_CLIP_H', '#define CPMAP_INTRO_CLIP_H',
             '#define CPMAP_INTRO_CLIP_FRAMES %dU' % aud, '#define CPMAP_INTRO_CLIP_FPS 30U',
             'static const unsigned char cpmap_intro_clip[%d] = {' % len(data)]
    for i in range(0, len(data), 24):
        lines.append(','.join('0x%02x' % b for b in data[i:i + 24]) + ',')
    lines += ['};', '#endif', '']
    return '\n'.join(lines)

clip, header = Path(sys.argv[1]), Path(sys.argv[2])
text = render(clip)
if '--check' in sys.argv[3:]:
    sys.exit(0 if header.read_text() == text else 'header does not match the clip')
header.write_text(text)
